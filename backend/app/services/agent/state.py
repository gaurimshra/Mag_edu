"""
LangGraph state definition for the adaptive learning agent.
"""

from typing import TypedDict, Annotated
import operator


class RAGChunk(TypedDict):
    id: int
    title: str
    body: str
    difficulty: str


class MistakeHistory(TypedDict):
    skill_id: str
    mistake_type: str
    count: int


class StudentState(TypedDict):
    # Inputs
    student_id: int
    skill_id: str
    skill_name: str
    mode: str           # "teach", "quiz", "simpler", "exercise"
    grade: int
    
    # Internal state gathered by nodes
    mastery_score: float
    difficulty_level: str  # "easy", "medium", "hard"
    mistake_patterns: list[MistakeHistory]
    recent_sessions: list[dict]
    rag_context: list[RAGChunk]
    
    # Outputs generated by LLM
    generated_content: str | dict | list
    generated_quiz_options: list[str] | None
    quiz_data: dict | None
    
    # Execution trace (optional)
    steps: Annotated[list[str], operator.add]
